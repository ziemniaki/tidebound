"""Map-qualified actor identities and explicit runtime roles, independent of labels."""

import json
from dataclasses import dataclass

from ..art import props
from ..files import ruby
from .definitions import DEFINITIONS

MAPS = {name: definition.id for name, definition in DEFINITIONS.items()}
MAP_NAMES = {value: key for key, value in MAPS.items()}


@dataclass(frozen=True)
class Actor:
    key: str
    map: str
    label: str
    role: str = "npc"
    species: str = ""


ACTORS = {}
for name, definition in DEFINITIONS.items():
    for key, fields in definition.actors.items():
        if key in ACTORS:
            raise ValueError(f"Duplicate actor identity: {key}")
        ACTORS[key] = Actor(key, name, **fields)

# Roles select concrete consumers in world/actors.rb and presentation modules.
ROLES = {
    "npc",
    "house",
    "room",
    "outside_dog",
    "spirit",
    "wood_bird",
    "neighbor_wild",
    "shore_duck",
    "keys",
    "crate",
    "fire",
    "main_lamp",
    "lamp",
    "lapras",
    "coast_lamp",
    "berry",
    "prop",
}


def validate_actor(info):
    role = info.get("role", "")
    if role and role not in ROLES:
        raise ValueError(f"Unknown actor role: {role}")
    if role in (
        "house",
        "room",
        "outside_dog",
        "wood_bird",
        "neighbor_wild",
        "shore_duck",
    ) and not info.get("species"):
        raise ValueError(f"Actor role {role} requires a species")
    if role == "spirit" and (type(info.get("index")) is not int or info["index"] < 0):
        raise ValueError("Spirit actor requires a nonnegative soul index")
    if role == "neighbor_wild" and not info.get("state"):
        raise ValueError("Neighbor wild actor requires its quest state key")
    if role == "prop" and not info.get("asset"):
        raise ValueError("Static prop requires an asset name")
    if info.get("cue") and info["cue"] not in ("north", "south", "east", "west"):
        raise ValueError(f"Unknown threshold direction: {info['cue']}")


def collect_actors(maps):
    actors, settings = {}, {}
    for area in maps:
        settings[area.id] = area.actor_settings
        for event_id, info in area.actor_settings.items():
            validate_actor(info)
            if event_id not in area.events:
                raise ValueError(f"Map {area.id}: actor refers to missing event {event_id}")
            key = info.get("key")
            if not key:
                continue
            if key in actors:
                raise ValueError(f"Duplicate actor identity: {key}")
            expected = ACTORS[key]
            if area.id != MAPS[expected.map]:
                raise ValueError(f"Actor {key} belongs to {expected.map}, not map {area.id}")
            actors[key] = {"map": area.id, "event": event_id}
    missing = ACTORS.keys() - actors.keys()
    if missing:
        raise ValueError("Missing world actors: " + ", ".join(sorted(missing)))
    return actors, settings


def write_registry(root, maps):
    if len(maps) != len(MAPS) or {area.id for area in maps} != set(MAPS.values()):
        raise ValueError("Authored maps and world registry disagree")
    actors, settings = collect_actors(maps)
    asset_events = [
        (mid, eid, info["asset"])
        for mid, events in settings.items()
        for eid, info in events.items()
        if info.get("asset")
    ]
    if asset_events:
        assets = props.load(root)
        for map_id, event_id, asset in asset_events:
            if asset not in assets:
                raise ValueError(f"Map {map_id} event {event_id}: unknown prop asset {asset}")
    lines = ["# Generated by the map compiler.", "module Tidebound", "  module World"]
    for name, records in [
        ("MAPS", MAPS),
        ("ACTORS", actors),
        ("ENTRANCES", {d.id: d.entrances for d in DEFINITIONS.values()}),
    ]:
        lines.append(f"    {name} = {{")
        lines.extend(
            f"      {str(key) + (':' if isinstance(key, str) else ' =>')} {ruby(value)},"
            for key, value in records.items()
        )
        lines.append("    }.freeze")
    lines.append("    ACTOR_SETTINGS = {")
    for map_id, events in settings.items():
        lines.append(f"      {map_id} => {{")
        lines.extend(
            f"        {event_id} => {ruby(info)}.freeze," for event_id, info in events.items()
        )
        lines.append("      }.freeze,")
    lines.append("    }.freeze")
    lines.append("    MAP_SETTINGS = {")
    for definition in DEFINITIONS.values():
        values = ", ".join(
            f"{key}: {json.dumps(value)}" for key, value in definition.runtime_settings().items()
        )
        lines.append(f"      {definition.id} => {{{values}}},")
    lines.append("    }.freeze")
    lines += ["  end", "end", ""]
    (root / "src/generated/world_registry.rb").write_text("\n".join(lines))
